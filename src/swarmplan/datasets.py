@dataclass(frozen=True)
class MapInfo:
    """A benchmark map we run on, with what it is meant to stress.

    ``height``, ``width`` and ``free_cells`` are read off the shipped map files
    by ``tools/fetch_benchmarks.py --describe``; they are recorded here so that
    a mis-download is caught before it turns into a wrong benchmark table.
    """

    name: str
    height: int
    width: int
    free_cells: int
    why: str


