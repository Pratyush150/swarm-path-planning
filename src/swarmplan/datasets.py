def default_data_dir() -> Path:
    """``<repo>/data``, where the fetch tool puts everything."""
    return Path(__file__).resolve().parents[2] / "data"


def map_path(name: str, data_dir: Optional[Path] = None) -> Path:
    """Path to a ``.map`` file (whether or not it has been fetched yet)."""
    data_dir = Path(data_dir) if data_dir else default_data_dir()
    return data_dir / "maps" / f"{name}.map"


def scen_path(
    map_name: str, index: int, kind: str = "random", data_dir: Optional[Path] = None
) -> Path:
    """Path to the ``index``-th scenario file of a map (1-based, as upstream)."""
    if kind not in ("random", "even"):
        raise ValueError("kind must be 'random' or 'even'")
    data_dir = Path(data_dir) if data_dir else default_data_dir()
    return data_dir / f"scen-{kind}" / f"{map_name}-{kind}-{index}.scen"


def available(data_dir: Optional[Path] = None) -> bool:
    """True if at least the maps and the random scenarios have been fetched.

    Every benchmark-dependent test is skipped on this, so a clone with no data
    still runs its whole unit suite.
    """
    data_dir = Path(data_dir) if data_dir else default_data_dir()
    if not (data_dir / "maps").is_dir():
        return False
    if not map_path("random-32-32-20", data_dir).exists():
        return False
    return scen_path("random-32-32-20", 1, "random", data_dir).exists()


def missing(data_dir: Optional[Path] = None) -> List[str]:
    """Which of the expected map files are absent."""
    data_dir = Path(data_dir) if data_dir else default_data_dir()
    return [m.name for m in MAPS if not map_path(m.name, data_dir).exists()]
