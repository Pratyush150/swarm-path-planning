"""The benchmark set: where it comes from, how to find it, how to check it.

We use the standard MAPF benchmark of Stern et al. (SoCS 2019), hosted with
Sturtevant's grid-pathfinding benchmarks at movingai.com. Nothing here is
generated by us and nothing here is committed to this repository: the maps and
scenarios are fetched by ``tools/fetch_benchmarks.py``, which verifies the
SHA-256 of every archive against the values recorded below.

Using this set rather than maps of our own is the point. Every success-rate
curve in the MAPF literature since 2019 is measured on these exact files with
these exact start/goal pairs, so a number produced here can be put next to a
published one.

Archive sizes and hashes below were recorded from the downloads this repository
was developed against; ``tools/fetch_benchmarks.py --verify`` re-checks them.
"""

